'use client';

import React from 'react';
import DOMPurify from 'dompurify';

interface RichTextDisplayProps {
  content: string;
  className?: string;
}

/**
 * Stored remarks are user-entered HTML. DOMPurify parses them in an inert document
 * (assigning innerHTML on a live element would already run `<img onerror>`) and drops
 * scripts and event handlers, keeping Tiptap's formatting, tables and lists.
 */
const sanitizeHtml = (html?: string): string => {
  if (!html || typeof window === 'undefined') return '';
  return DOMPurify.sanitize(html);
};

